/**
 * 空间、层级与动效：圆角、z 序、时长、缓动、断点。
 *
 * # 为什么没有间距刻度
 *
 * 间距用 UnoCSS 自带的数值刻度（`p-4` = 1rem）。自建一套的后果不是"更统一"，而是**同屏出现两种
 * 4px 的倍数**：一处用 `p-4`，另一处用 `p-[14px]`，而它们看起来都在遵守规范。
 *
 * # 为什么圆角与层级是名字，不是数字
 *
 * 圆角**分层**：控件 / 面 / 胶囊，三个值必须能一眼分开，否则等于没有层级。z 序同理 ——
 * 宿主主文档里的浮层互相盖是唯一一类"看起来对、就是点不到"的 bug，所以用名字不用数字。
 */

/** 圆角**分层**：控件 / 面 / 胶囊。三个值必须能一眼分开，否则等于没有层级。 */
export const radius = {
  control: '8px',
  surface: '12px',
  pill: '999px',
} as const

/** 层级。宿主主文档里的浮层互相盖是唯一一类"看起来对、就是点不到"的 bug，所以用名字不用数字。 */
export const zIndex = {
  base: 0,
  panel: 10,
  overlay: 20,
  modal: 30,
  toast: 40,
  drag: 50,
} as const

/** 时长。字面 `300ms` 不许出现在源码里，否则"整体调慢一点"是一次全仓搜索。 */
export const duration = {
  fast: '120ms',
  base: '180ms',
  slow: '280ms',
} as const

export const ease = {
  standard: 'cubic-bezier(0.32, 0.72, 0, 1)',
} as const

/**
 * 断点用**标准数值**，不发明自己的名字与数字。
 *
 * 插件作者是第三方，`md: 768` 是他们的肌肉记忆；发明一套自定义断点会让每个人在第一次写响应式时
 * 踩一次坑。而每一档"做什么"必须写死（见设计文档 28 §4 R11 的表），那才是这条规则要立的东西。
 *
 * 宿主的最小窗口是 1024（`tauri.conf.json` 的 `minWidth`），与 `lg` 相等 —— 于是"任何用户能拖到的
 * 尺寸"都落在某个设计过的档位上。
 */
export const breakpoints = {
  'sm': '640px',
  'md': '768px',
  'lg': '1024px',
  'xl': '1280px',
  '2xl': '1536px',
} as const
